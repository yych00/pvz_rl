def unlocked_plants(level_id):
    return (0,) + tuple(plant for earned_at, plant in PLANT_REWARDS.items() if earned_at < level_id)


@dataclass(frozen=True)
class AdventureDeckProfile:
    level_id: int
    playthrough: int
    primary: tuple[int, ...]
    candidates: tuple[int, ...]
    new_plants: tuple[int, ...]
    new_zombies: tuple[int, ...]
    lesson: str
    special: str | None


def deck_profile(level_id, playthrough):
    if type(level_id) is not int or not 1 <= level_id <= 50:
        raise ValueError("level_id must be 1..50")
    if type(playthrough) is not int or playthrough not in (1, 2):
        raise ValueError("playthrough must be 1 or 2")
    allowed = unlocked_plants(level_id) if playthrough == 1 else tuple(range(40))
    # Profiles for non-chooser levels describe the relevant lesson, but actual
    # reset/selection respects the game's conveyor / preplaced plants.
    primary = tuple(p for p in (FIRST_DECKS if playthrough == 1 else SECOND_DECKS)[level_id]
                    if p in allowed)
    scene = (level_id - 1) // 10
    backups = (
        (17, 2, 20, 4, 5, 6, 3, 7, 0, 21, 23, 30, 1),
        (12, 14, 15, 2, 3, 10, 13, 7, 5, 6, 31, 23, 39, 1),
        (19, 17, 2, 20, 21, 23, 18, 5, 3, 7, 6, 4, 0, 30, 1, 8),
        (24, 25, 26, 27, 28, 29, 31, 23, 17, 2, 20, 30, 19, 10, 14, 15, 8, 9),
        (34, 32, 39, 37, 17, 2, 20, 23, 30, 35, 31, 4, 36, 38, 1, 33),
    )[scene]
    # An ordered, explicit fallback pool rather than raw plant-ID filling.
    candidates = tuple(dict.fromkeys(p for p in (*backups, *allowed)
                                    if p in allowed and p not in primary))
    # Fog defaults use mushrooms for opening defense; do not refill Potato Mine.
    if scene == 3:
        candidates = tuple(p for p in candidates if p != 4)
    introduced = ZOMBIE_INTRODUCTIONS.get(level_id, ())
    if playthrough == 2 and level_id == 40:
        introduced += (19,)
    reward = PLANT_REWARDS.get(level_id - 1)
    return AdventureDeckProfile(level_id, playthrough, primary, candidates,
                                (reward,) if reward is not None else ((0,) if level_id == 1 else ()),
                                introduced, LESSONS[level_id], SPECIAL_LEVELS.get(level_id))
